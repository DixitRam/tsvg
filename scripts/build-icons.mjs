// libs/icons/icons.tsvgl from Lucide (ISC): every icon as one path (circles, rects, lines, polylines become path data),
// so one stroke draws it and draw= animates it. Usage: npm pack lucide-static && tar xzf … ; node scripts/build-icons.mjs <lucide-static dir>
import { readFileSync, writeFileSync } from 'node:fs';
const dir = process.argv[2] || '/tmp/lucide/package';
const nodes = JSON.parse(readFileSync(dir + '/icon-nodes.json', 'utf8'));
const version = JSON.parse(readFileSync(dir + '/package.json', 'utf8')).version;
const n = (v) => +(+v).toFixed(3);
function toD(tag, a) {
  switch (tag) {
    case 'path': return a.d;
    case 'circle': { const x = n(a.cx), y = n(a.cy), r = n(a.r); return `M${n(x - r)} ${y}a${r} ${r} 0 1 0 ${n(2 * r)} 0a${r} ${r} 0 1 0 ${n(-2 * r)} 0`; }
    case 'ellipse': { const x = n(a.cx), y = n(a.cy), rx = n(a.rx), ry = n(a.ry); return `M${n(x - rx)} ${y}a${rx} ${ry} 0 1 0 ${n(2 * rx)} 0a${rx} ${ry} 0 1 0 ${n(-2 * rx)} 0`; }
    case 'line': return `M${n(a.x1)} ${n(a.y1)}L${n(a.x2)} ${n(a.y2)}`;
    case 'polyline': case 'polygon': { const p = a.points.trim().split(/[\s,]+/).map(n); let d = ''; for (let i = 0; i < p.length; i += 2) d += (i ? 'L' : 'M') + p[i] + ' ' + p[i + 1]; return d + (tag === 'polygon' ? 'Z' : ''); }
    case 'rect': {
      const x = n(a.x || 0), y = n(a.y || 0), w = n(a.width), h = n(a.height), r = Math.min(n(a.rx || a.ry || 0), w / 2, h / 2);
      if (!r) return `M${x} ${y}H${n(x + w)}V${n(y + h)}H${x}Z`;
      return `M${n(x + r)} ${y}H${n(x + w - r)}A${r} ${r} 0 0 1 ${n(x + w)} ${n(y + r)}V${n(y + h - r)}A${r} ${r} 0 0 1 ${n(x + w - r)} ${n(y + h)}H${n(x + r)}A${r} ${r} 0 0 1 ${x} ${n(y + h - r)}V${n(y + r)}A${r} ${r} 0 0 1 ${n(x + r)} ${y}Z`;
    }
  }
  throw new Error('unknown tag ' + tag);
}
const esc = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const names = Object.keys(nodes).sort();
const entries = names.map((k) => `    <e k="${k}" v="${esc(nodes[k].map(([t, a]) => toD(t, a)).join(''))}"/>`).join('\n');
const out = `<?xml version="1.0" encoding="UTF-8"?>
<!--
  tsvg:icons — ${names.length} line icons from Lucide ${version} (ISC licence, lucide.dev; see LICENSE-lucide.txt). Generated by scripts/build-icons.mjs.
    <import src="tsvg:icons" as="i"/>
    <i:icon name="rocket" size="96" color="$accent"/>                  one icon, centred on x, y
    <i:icon name="check" size="64" color="$good" drawin="0.8" at="1"/>   drawn in over 0.8 s from at
  Names: https://lucide.dev/icons (kebab-case, e.g. arrow-right, circle-check, chart-bar).
-->
<tsvglib name="icons" version="1.0.0" doc="${names.length} Lucide line icons (ISC): <i:icon name size color sw drawin at x y/>; names as on lucide.dev/icons.">
  <dict id="d">
${entries}
  </dict>
  <component id="icon" props="name, size=64, color=$fg, sw=2, x=0, y=0, at=0, drawin=0, fill=none"
             doc="One Lucide icon centred on x, y. size in layout units, sw stroke width in icon units (24 per side), drawin = seconds to draw it in from at.">
    <group x="%{x}" y="%{y}" w="%{size}" h="%{size}" ax="0.5" ay="0.5" at="%{at}">
      <path scale="=%{size}/24" d="%{d[name]}" fill="%{fill}" stroke="%{color}" sw="%{sw}" draw="=%{drawin} > 0 ? ease(clamp((T - T0) / max(0.001, %{drawin}), 0, 1), 'io') : 1"/>
    </group>
  </component>
</tsvglib>
`;
writeFileSync(new URL('../libs/icons/icons.tsvgl', import.meta.url), out);
writeFileSync(new URL('../libs/icons/LICENSE-lucide.txt', import.meta.url), readFileSync(dir + '/LICENSE'));
console.log('libs/icons/icons.tsvgl', names.length, 'icons', (out.length / 1024).toFixed(0) + ' KB');
